"""SOP dict -> a single self-contained HTML file (images embedded)."""
import base64, html, os

def _img(path):
    if not path or not os.path.exists(path):
        return ""
    b64 = base64.b64encode(open(path, "rb").read()).decode()
    return f'<img src="data:image/jpeg;base64,{b64}" alt="">'

def export_html(sop, out_path):
    e = html.escape
    rows = []
    for s in sop["steps"]:
        warn = f'<p class="warn">⚠ {e(s["warning"])}</p>' if s.get("warning") else ""
        check = f'<p class="check">✓ Check: {e(s["check"])}</p>' if s.get("check") else ""
        t = f'{s["start"]:.0f}–{s["end"]:.0f} s' if "start" in s else ""
        rows.append(f"""
<section class="step">
  <div class="num">{s["number"]}</div>
  <div class="body">
    <h2>{e(s["title"])} <span class="t">{t}</span></h2>
    <p>{e(s["instruction"])}</p>{check}{warn}
  </div>
  <div class="pic">{_img(s.get("image"))}</div>
</section>""")
    lists = ""
    for label, key in (("Tools", "tools"), ("Parts", "parts")):
        if sop.get(key):
            lists += f"<p><b>{label}:</b> {e(', '.join(sop[key]))}</p>"
    doc = f"""<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(sop["title"])}</title>
<style>
 body{{font-family:system-ui,sans-serif;max-width:960px;margin:2rem auto;padding:0 16px;color:#1c1c1c;background:#fafaf8}}
 h1{{margin-bottom:.2rem}} .meta{{color:#555}}
 .step{{display:grid;grid-template-columns:48px 1fr 320px;gap:16px;align-items:start;
        background:#fff;border:1px solid #e4e4e0;border-radius:10px;padding:16px;margin:14px 0}}
 .num{{font-size:1.6rem;font-weight:700;color:#0a66c2}}
 h2{{font-size:1.1rem;margin:0 0 .4rem}} .t{{font-weight:400;color:#888;font-size:.85rem}}
 .pic img{{width:100%;border-radius:6px}}
 .check{{color:#1d7a35}} .warn{{color:#a4540c}}
 @media(max-width:700px){{.step{{grid-template-columns:36px 1fr}} .pic{{grid-column:1/-1}}}}
</style></head><body>
<h1>{e(sop["title"])}</h1>
<p class="meta">{e(sop.get("purpose", ""))}</p>{lists}
{''.join(rows)}
<p class="meta">Generated by Stepwise from a narrated video with Muse Voice Transcribe, SAM 3.1 and Muse Spark.</p>
</body></html>"""
    open(out_path, "w", encoding="utf-8").write(doc)
    return out_path
